import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { basename, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { DatabaseSync } from "node:sqlite";
import { build } from "esbuild";

const root = fileURLToPath(new URL("../../", import.meta.url));
const q = value => `'${String(value).replaceAll("'", "''")}'`;

async function loadSource(entryPoint) {
  const result = await build({ absWorkingDir: root, entryPoints: [entryPoint], bundle: true, write: false, platform: "node", format: "cjs", target: "node22" });
  const module = { exports: {} };
  new Function("module", "exports", "require", result.outputFiles[0].text)(module, module.exports, () => { throw new Error("Unexpected runtime dependency"); });
  return module.exports;
}

export async function prepareAuthoredImport(options) {
  const { projectId, assetDirectory, createdAt, actor, isFeatured, scriptName, importSource, label } = options;
  const [{ portfolioProjects }, contracts] = await Promise.all([loadSource("app/portfolio/data.ts"), loadSource("shared/contracts/index.ts")]);
  const project = portfolioProjects.find(project => project.id === projectId);
  assert.ok(project?.document && project.media, `${label} source document and media are required.`);
  const metadata = {
    categoryId: project.primaryCategory, title: project.title, shortTitle: project.shortTitle, subtitle: project.summary,
    thumbnailAssetId: project.media.find(asset => asset.url === project.thumbnail.src)?.id,
    coverAssetId: project.media.find(asset => asset.url === project.cover.src)?.id,
    tags: project.tags, tools: project.tools, role: project.role, year: project.year, isFeatured, sortOrder: project.order,
  };
  const metadataValidation = contracts.validateProjectMetadata(metadata);
  const documentValidation = contracts.validateArticleDocument(project.document);
  assert.equal(metadataValidation.ok, true, `${label} metadata must satisfy the shared contract.`);
  assert.equal(documentValidation.ok, true, `${label} document must satisfy the shared contract.`);
  const referenced = new Set([metadata.thumbnailAssetId, metadata.coverAssetId, ...contracts.collectArticleAssetIds(project.document)]);
  assert.deepEqual([...referenced].sort(), project.media.map(asset => asset.id).sort());
  const media = await Promise.all(project.media.map(async asset => {
    const filePath = resolve(root, asset.url.replace(/^\.\//, ""));
    assert.ok(filePath.startsWith(resolve(root, `public/portfolio/${assetDirectory}`) + sep), "Import may read only the collection's public assets.");
    const bytes = await readFile(filePath);
    const checksum = createHash("sha256").update(bytes).digest("hex");
    return { ...asset, sourcePath: asset.url, originalName: basename(filePath), bytes: bytes.length, checksum,
      objectKey: `portfolio/${assetDirectory}/${asset.id}-${checksum.slice(0, 16)}.webp` };
  }));
  const revisionId = project.revisionId;
  const metaJson = JSON.stringify(metadataValidation.value);
  const bodyJson = JSON.stringify(documentValidation.value);
  const initialDraft = `id = ${q(project.id)} AND draft_version = 1 AND created_at = ${q(createdAt)} AND updated_at = ${q(createdAt)}`;
  const sql = [`-- Generated by ${scriptName}; local import only.`, "PRAGMA foreign_keys = ON;"];
  for (const asset of media) sql.push(`INSERT INTO media_assets (id, object_key, original_name, mime, bytes, width, height, alt_default, checksum, state, created_by, created_at) VALUES (${q(asset.id)}, ${q(asset.objectKey)}, ${q(asset.originalName)}, ${q(asset.mime)}, ${asset.bytes}, ${asset.width}, ${asset.height}, ${q(asset.alt)}, ${q(asset.checksum)}, 'ready', ${q(actor)}, ${q(createdAt)}) ON CONFLICT(id) DO NOTHING;`);
  sql.push(`INSERT INTO projects (id, slug, draft_meta_json, draft_body_json, draft_version, created_at, updated_at) VALUES (${q(project.id)}, ${q(projectId)}, ${q(metaJson)}, ${q(bodyJson)}, 1, ${q(createdAt)}, ${q(createdAt)}) ON CONFLICT(id) DO NOTHING;`);
  sql.push(`INSERT INTO project_revisions (id, project_id, source_version, meta_json, body_json, schema_version, created_by, created_at) SELECT ${q(revisionId)}, id, 1, ${q(metaJson)}, ${q(bodyJson)}, 1, ${q(actor)}, ${q(createdAt)} FROM projects WHERE ${initialDraft} ON CONFLICT(id) DO NOTHING;`);
  for (const id of referenced) {
    sql.push(`INSERT INTO revision_assets (revision_id, asset_id) SELECT ${q(revisionId)}, ${q(id)} WHERE EXISTS (SELECT 1 FROM project_revisions WHERE id = ${q(revisionId)}) ON CONFLICT(revision_id, asset_id) DO NOTHING;`);
    sql.push(`INSERT INTO draft_assets (project_id, asset_id) SELECT id, ${q(id)} FROM projects WHERE ${initialDraft} ON CONFLICT(project_id, asset_id) DO NOTHING;`);
  }
  const searchText = contracts.normalizeSearchText([metadata.title, metadata.shortTitle, metadata.subtitle, ...metadata.tags, ...metadata.tools].join(" "));
  sql.push(`INSERT INTO public_projects (project_id, revision_id, category_id, title, short_title, subtitle, thumbnail_asset_id, sort_order, is_featured, search_text, content_state, published_at) SELECT id, ${q(revisionId)}, ${q(metadata.categoryId)}, ${q(metadata.title)}, ${q(metadata.shortTitle)}, ${q(metadata.subtitle)}, ${q(metadata.thumbnailAssetId)}, ${metadata.sortOrder}, ${metadata.isFeatured ? 1 : 0}, ${q(searchText)}, 'ready', ${q(createdAt)} FROM projects WHERE ${initialDraft} AND EXISTS (SELECT 1 FROM project_revisions WHERE id = ${q(revisionId)}) ON CONFLICT(project_id) DO NOTHING;`);
  sql.push(`INSERT INTO audit_events (id, actor_sub, action, entity_type, entity_id, request_id, detail_json, created_at) SELECT ${q(`audit-${assetDirectory}-v1`)}, ${q(actor)}, 'project.publish', 'project', id, ${q(options.requestId ?? `${assetDirectory}-collection-v1`)}, ${q(JSON.stringify({ revisionId, source: importSource }))}, ${q(createdAt)} FROM projects WHERE ${initialDraft} ON CONFLICT(id) DO NOTHING;`);
  for (const retiredId of options.retireProjectIds ?? []) {
    sql.push(`UPDATE projects SET deleted_at = ${q(createdAt)}, updated_at = ${q(createdAt)}, draft_version = draft_version + 1 WHERE id = ${q(retiredId)} AND deleted_at IS NULL;`);
    sql.push(`DELETE FROM public_projects WHERE project_id = ${q(retiredId)};`);
    sql.push(`INSERT INTO audit_events (id, actor_sub, action, entity_type, entity_id, request_id, detail_json, created_at) VALUES (${q(`audit-retire-${retiredId}`)}, ${q(actor)}, 'project.trash', 'project', ${q(retiredId)}, ${q(options.requestId ?? `${assetDirectory}-collection-v1`)}, ${q(JSON.stringify({ source: importSource, reason: "Replaced by Exhibition Booth 1" }))}, ${q(createdAt)}) ON CONFLICT(id) DO NOTHING;`);
  }
  return { content: { id: project.id, slug: projectId, revisionId, createdAt, metadata: metadataValidation.value, document: documentValidation.value, media }, sql: sql.join("\n") + "\n" };
}

export async function runLocalAuthoredImport(options) {
  if (process.argv.slice(2).some(arg => arg !== "--prepare")) throw new Error("Only --prepare is supported; this importer never accesses remote D1/R2.");
  const prepared = await prepareAuthoredImport(options);
  const contentDirectory = resolve(root, "db/content");
  const scratch = resolve(root, `.tmp/admin-integration/${options.assetDirectory}`);
  await Promise.all([mkdir(contentDirectory, { recursive: true }), mkdir(scratch, { recursive: true })]);
  const sqlPath = resolve(contentDirectory, `${options.projectId}.sql`);
  await Promise.all([writeFile(sqlPath, prepared.sql), writeFile(resolve(contentDirectory, `${options.projectId}.json`), JSON.stringify(prepared.content, null, 2) + "\n")]);
  if (process.argv.includes("--prepare")) { console.log(`Prepared ${options.label} content and validated all ${prepared.content.media.length} asset references.`); return; }
  const execFileAsync = promisify(execFile);
  const wrangler = resolve(root, "node_modules/wrangler/bin/wrangler.js");
  const run = async args => {
    try { await execFileAsync(process.execPath, [wrangler, ...args], {
      cwd: root, maxBuffer: 8 * 1024 * 1024,
      env: { ...process.env, CI: "true", WRANGLER_SEND_METRICS: "false", WRANGLER_LOG_PATH: resolve(scratch, "wrangler.log") },
    }); } catch (error) { throw new Error(`Local Wrangler command failed: ${args.slice(0, 3).join(" ")}\n${error.stderr || error.message}`); }
  };
  for (const target of [
    { name: "public", config: "workers/public/wrangler.jsonc", state: ".wrangler/state" },
    { name: "admin", config: "workers/admin/wrangler.jsonc", state: ".wrangler/admin/state" },
  ]) {
    const state = resolve(root, target.state);
    const local = ["--local", "--persist-to", state, "--config", target.config];
    await run(["d1", "migrations", "apply", "DB", ...local]);
    const databaseDirectory = resolve(state, "v3/d1/miniflare-D1DatabaseObject");
    const databases = (await readdir(databaseDirectory)).filter(name => name.endsWith(".sqlite") && name !== "metadata.sqlite");
    assert.ok(databases.length > 0, "A local content database is required.");
    for (const name of databases) {
      const database = new DatabaseSync(resolve(databaseDirectory, name), { readOnly: true });
      try { database.exec(`VACUUM INTO ${q(resolve(scratch, `${target.name}-${name}-before-${Date.now()}.sqlite`))}`); }
      finally { database.close(); }
    }
    for (const asset of prepared.content.media) await run(["r2", "object", "put", `hyperd-media-staging/${asset.objectKey}`, ...local,
      "--file", resolve(root, asset.sourcePath.replace(/^\.\//, "")), "--content-type", asset.mime, "--cache-control", "private, no-store", "--force"]);
    await run(["d1", "execute", "DB", ...local, "--file", sqlPath]);
    console.log(`Imported ${options.label} into ${target.name} local state; backed up the database and kept existing content intact.`);
  }
}


